// Builds ui/icons.js from the Lucide set. Run: npm run icons
const fs = require('fs'), path = require('path')
const NAMES = ['arrow-left', 'arrow-right', 'rotate-cw', 'lock', 'plus', 'volume-2', 'volume-x', 'pin', 'moon', 'x',
  'shield-check', 'shield-off', 'eye-off', 'shield-alert', 'search', 'globe', 'house', 'briefcase', 'gamepad-2', 'triangle-alert', 'layers', 'loader-circle',
  'star', 'folder', 'folder-plus', 'chevron-right', 'chevron-down', 'columns-2', 'panel-left', 'download', 'history', 'archive', 'settings',
  'key-round', 'play', 'pause', 'external-link', 'trash-2', 'image', 'file', 'puzzle', 'printer', 'music', 'keyboard', 'check', 'route',
  'user-round', 'undo-2']
const dir = path.join(__dirname, '..', 'node_modules', 'lucide-static', 'icons')
const nodes = Object.fromEntries(NAMES.map(n => [n, fs.readFileSync(path.join(dir, n + '.svg'), 'utf8').replace(/<!--[\s\S]*?-->|<svg[^>]*>|<\/svg>/g, '').replace(/\s+/g, ' ').trim()]))
fs.writeFileSync(path.join(__dirname, '..', 'ui', 'icons.js'), `// generated by scripts/gen-icons.js (Lucide, ISC)
const NODES = ${JSON.stringify(nodes)}
window.icon = (n, s = 16) => \`<svg class="ic" width="\${s}" height="\${s}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${NODES[n] || NODES.globe}</svg>\`
`)
